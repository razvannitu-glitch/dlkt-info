// Server-only laboratory contract. This port is not a production database adapter.
import {record,field,stripeId,unixSeconds} from '../../source/src/billing/records.js';
import {isUuid} from '../../source/src/data/guards.js';
import type {PremiumPlan} from '../../source/src/billing/catalog.js';
import type {SandboxHostedSessions,Checkout,CheckoutTerminal,Failed} from './hosted-sessions.js';

type Reservation=Readonly<{accountId:string;ownerId:string;customerId:string;intentId:string;priceId:string;
  liveMode:false;createdAt:number;expiresAt:number;sessionId:string|null;closedAt:null;state:'reserved'|'attached'}>;
type Attachment=Readonly<{accountId:string;ownerId:string;customerId:string;intentId:string;priceId:string;sessionId:string;expiresAt:number}>;
type Terminal=Readonly<Attachment&{status:CheckoutTerminal['status'];paymentStatus:CheckoutTerminal['paymentStatus'];subscriptionId:string|null;itemId:string|null}>;
export interface CheckoutApiStore {
  reserve(accountId:string,ownerId:string,plan:PremiumPlan,requestId:string):Promise<unknown>;
  attach(record:Attachment):Promise<unknown>;
}
export interface CheckoutRecoveryStore {
  load(accountId:string,intentId:string):Promise<unknown>;
  attach(record:Attachment):Promise<unknown>;
  finish(record:Terminal):Promise<unknown>;
}
const FAILED:Failed=Object.freeze({kind:'unavailable'});
const get=(v:unknown,k:string):unknown=>field(record(v),k);
function checkoutId(v:unknown):v is string{return typeof v==='string'&&/^cs_test_[A-Za-z0-9]{1,247}$/u.test(v);}
function reservation(raw:unknown,account:string):Reservation|null{
  const ownerId=get(raw,'ownerId'),customerId=get(raw,'customerId'),intentId=get(raw,'intentId'),priceId=get(raw,'priceId'),
    createdAt=get(raw,'createdAt'),expiresAt=get(raw,'expiresAt'),sessionId=get(raw,'sessionId'),state=get(raw,'state');
  if(get(raw,'accountId')!==account||!isUuid(ownerId)||!stripeId(customerId,'cus')||!isUuid(intentId)||!stripeId(priceId,'price')
    ||get(raw,'liveMode')!==false||get(raw,'closedAt')!==null||!unixSeconds(createdAt)||!unixSeconds(expiresAt)||expiresAt!==createdAt+3600
    ||!((state==='reserved'&&sessionId===null)||(state==='attached'&&checkoutId(sessionId))))return null;
  return Object.freeze({accountId:account,ownerId,customerId,intentId,priceId,createdAt,expiresAt,sessionId,closedAt:null,liveMode:false,state});
}
function attachment(i:Reservation,p:Checkout|CheckoutTerminal):Attachment|null{
  if(!checkoutId(p.sessionId)||p.expiresAt!==i.expiresAt||(i.sessionId!==null&&i.sessionId!==p.sessionId))return null;
  return Object.freeze({accountId:i.accountId,ownerId:i.ownerId,customerId:i.customerId,intentId:i.intentId,priceId:i.priceId,sessionId:p.sessionId,expiresAt:i.expiresAt});
}
type RecoveryResult=Readonly<{kind:'attached'|'expired'|'complete'|'unavailable'}>;
type Provider=Pick<SandboxHostedSessions,'createCheckout'|'observeCheckout'>;
const currentTime=()=>Math.floor(Date.now()/1000);
/**
 * Inputs owner and request ID must be resolved/generated by the authenticated
 * server, not the browser. The DB reservation fixes plan and customer.
 * The provider call is outside the DB transaction; ambiguity keeps the slot
 * reserved. Return the bearer-like hosted URL only AFTER durable attachment.
 */
export async function beginCheckout(accountId:unknown,ownerId:unknown,plan:unknown,requestId:unknown,store:CheckoutApiStore,provider:Provider,clock:()=>number=currentTime):Promise<Checkout|Failed>{
  try{
    if(!stripeId(accountId,'acct')||!isUuid(ownerId)||!isUuid(requestId)||(plan!=='monthly'&&plan!=='annual'))return FAILED;
    const i=reservation(await store.reserve(accountId,ownerId,plan,requestId),accountId);
    if(!i||i.ownerId!==ownerId)return FAILED;
    const now=clock();
    if(!unixSeconds(now)||now<i.createdAt||now>=i.expiresAt)return FAILED;
    // A reservation older than 10 minutes or an attached session is read-only.
    const p=i.sessionId!==null||now-i.createdAt>600
      ?await provider.observeCheckout(ownerId,i,i,now):await provider.createCheckout(ownerId,i,i,now);
    if(p.kind!=='checkout')return FAILED;
    const a=attachment(i,p),checked=clock();
    if(!a||!unixSeconds(checked)||checked<now||checked>=i.expiresAt)return FAILED;
    if(await store.attach(a)!==true)return FAILED;
    const finalTime=clock();
    if(!unixSeconds(finalTime)||finalTime<checked||finalTime>=i.expiresAt)return FAILED;
    return p;
  }catch{return FAILED;}
}
/** No creation or redirect exposure in background recovery. If provider state
 * is ambiguous or storage is unavailable, keep the intent and retry later. */
export async function recoverCheckout(accountId:unknown,intentId:unknown,store:CheckoutRecoveryStore,provider:Pick<Provider,'observeCheckout'>,clock:()=>number=currentTime):Promise<RecoveryResult>{
  try{
    if(!stripeId(accountId,'acct')||!isUuid(intentId))return FAILED;
    const i=reservation(await store.load(accountId,intentId),accountId);
    if(!i||i.intentId!==intentId)return FAILED;
    const now=clock();
    if(!unixSeconds(now)||now<i.createdAt)return FAILED;
    const p=await provider.observeCheckout(i.ownerId,i,i,now);
    if(p.kind==='unavailable')return FAILED;
    const a=attachment(i,p);if(!a)return FAILED;
    if(p.kind==='checkout'){
      const checked=clock();
      if(!unixSeconds(checked)||checked<now||checked>=i.expiresAt||await store.attach(a)!==true)return FAILED;
      return Object.freeze({kind:'attached'});
    }
    if(await store.finish({...a,status:p.status,paymentStatus:p.paymentStatus,subscriptionId:p.subscriptionId,itemId:p.itemId})!==true)return FAILED;
    return Object.freeze({kind:p.status});
  }catch{return FAILED;}
}
