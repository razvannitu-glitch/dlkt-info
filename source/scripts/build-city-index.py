"""Build a reviewed GeoNames cities15000 snapshot; never run at request time."""
import json,zipfile,hashlib,datetime,sys,pathlib,math
root=pathlib.Path(sys.argv[1])
admin={x[0]:x[1] for line in (root/'admins.txt').read_text().splitlines() if len(x:=line.split('\t'))>=2}
countries={x[0]:x[4] for line in (root/'countries.txt').read_text().splitlines() if not line.startswith('#') and len(x:=line.split('\t'))>=5}
with zipfile.ZipFile(root/'geocities.zip') as z:
 info=z.getinfo('cities15000.txt');assert info.file_size<100_000_000
 lines=z.read(info).decode('utf-8').splitlines()
rows=[];rejected=0
for line in lines:
 c=line.split('\t')
 try:
  assert len(c)==19 and c[6]=='P' and c[8] in countries
  lat,lon=float(c[4]),float(c[5]);assert math.isfinite(lat) and math.isfinite(lon) and -90<=lat<=90 and -180<=lon<=180
  assert c[0].isdigit() and c[1] and c[17] and len(c[1])<=200
  aliases=list(dict.fromkeys([c[2],*c[3].split(',')]))
  rows.append([c[0],c[1],c[8],countries[c[8]],admin.get(c[8]+'.'+c[10],c[10]),round(lat,4),round(lon,4),c[17],max(0,int(c[14])),[a for a in aliases if a and a!=c[1] and len(a)<=120][:128]])
 except (ValueError,AssertionError):rejected+=1
assert len({r[0] for r in rows})==len(rows) and len(rows)>20000
rows.sort(key=lambda r:(-r[8],r[0]))
data={'version':'dlkt-cities-1','generatedAt':datetime.datetime.now(datetime.timezone.utc).isoformat(),'source':'https://download.geonames.org/export/dump/cities15000.zip','license':'https://creativecommons.org/licenses/by/4.0/','scope':'GeoNames cities15000: larger cities and capitals, not every village or address. City-centre coordinates.','columns':['id','name','countryCode','country','region','lat','lon','timezone','population','aliases'],'rows':rows}
raw=json.dumps(data,ensure_ascii=False,separators=(',',':'))
# A plain string avoids generating thousands of inferred TypeScript tuple types.
pathlib.Path('src/local/city-data.ts').write_text('// Generated by scripts/build-city-index.py. GeoNames CC BY 4.0; see CITY-SOURCES.json.\nexport const cityJson: string = '+json.dumps(raw,ensure_ascii=False)+';\n')
manifest={'generatedAt':data['generatedAt'],'count':len(rows),'rejected':rejected,'license':data['license'],'scope':data['scope'],'inputs':{f:hashlib.sha256((root/f).read_bytes()).hexdigest() for f in ['geocities.zip','admins.txt','countries.txt']},'outputSha256':hashlib.sha256(raw.encode()).hexdigest()}
pathlib.Path('CITY-SOURCES.json').write_text(json.dumps(manifest,indent=2))
print(json.dumps({'count':len(rows),'rejected':rejected,'bytes':len(raw.encode()),'examples':[r[:9] for r in rows if r[0] in ['683506','2643743','5128581','1850147']]}))
